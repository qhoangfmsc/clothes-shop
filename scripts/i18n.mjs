#!/usr/bin/env node
/**
 * i18n tooling.
 *
 *   node scripts/i18n.mjs sync    regenerate src/i18n/registry.ts from src/messages/en/**
 *   node scripts/i18n.mjs check   verify every locale mirrors `en` (files, keys, {placeholders}, empty values)
 *
 * `sync` runs automatically before `dev` / `build`; `check` runs before `build` and in `yarn lint:i18n`.
 */
import { readdirSync, readFileSync, writeFileSync, statSync, existsSync } from "node:fs";
import { join, relative, sep } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(fileURLToPath(new URL(".", import.meta.url)), "..");
const MESSAGES_DIR = join(ROOT, "src/messages");
const REGISTRY_FILE = join(ROOT, "src/i18n/registry.ts");
const SOURCE_LOCALE = "en";

/** `["vi","en"]` read from routing.ts so there is one list of languages. */
function readLocales() {
  const routing = readFileSync(join(ROOT, "src/i18n/routing.ts"), "utf8");
  const match = routing.match(/locales:\s*\[([^\]]+)\]/);
  if (!match) throw new Error("Cannot find `locales: [...]` in src/i18n/routing.ts");
  return [...match[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : [full];
  });
}

/** Message files of one locale as sorted keys like "admin/products". */
function listFiles(locale) {
  const base = join(MESSAGES_DIR, locale);
  if (!existsSync(base)) return [];
  return walk(base)
    .filter((f) => f.endsWith(".json"))
    .map((f) =>
      relative(base, f)
        .split(sep)
        .join("/")
        .replace(/\.json$/, "")
    )
    .sort();
}

function renderRegistry(files) {
  const lines = files.map(
    (f) => `  "${f}": load<typeof import("../messages/${SOURCE_LOCALE}/${f}.json")>("${f}"),`
  );
  return `/* AUTO-GENERATED by scripts/i18n.mjs (yarn i18n:sync) — do not edit by hand.
   One entry per file in src/messages/${SOURCE_LOCALE}/. The \`en\` JSON files are the source of truth for types. */
import type { AppLocale } from "./routing";

const load =
  <T>(file: string) =>
  (locale: AppLocale) =>
    import(\`../messages/\${locale}/\${file}.json\`) as Promise<{ default: T }>;

export const MESSAGE_FILES = {
${lines.join("\n")}
} as const;
`;
}

function sync() {
  const next = renderRegistry(listFiles(SOURCE_LOCALE));
  const prev = existsSync(REGISTRY_FILE) ? readFileSync(REGISTRY_FILE, "utf8") : "";
  if (next !== prev) {
    writeFileSync(REGISTRY_FILE, next);
    console.log("i18n: registry updated");
  }
}

/** Flatten nested JSON into { "a.b.c": "text" }. */
function flatten(obj, prefix = "", out = {}) {
  for (const [key, value] of Object.entries(obj)) {
    const path = prefix ? `${prefix}.${key}` : key;
    if (value && typeof value === "object") flatten(value, path, out);
    else out[path] = value;
  }
  return out;
}

/** Top-level ICU argument names: {name}, {count, plural, ...} -> name, count. Nested branches are ignored. */
function placeholders(text) {
  const names = new Set();
  let depth = 0;
  let start = -1;
  for (let i = 0; i < text.length; i++) {
    if (text[i] === "{") {
      if (depth === 0) start = i + 1;
      depth++;
    } else if (text[i] === "}") {
      depth--;
      if (depth === 0 && start >= 0) {
        names.add(text.slice(start, i).split(",")[0].trim());
        start = -1;
      }
    }
  }
  return [...names].sort().join(",");
}

function check() {
  const locales = readLocales();
  const errors = [];
  const sourceFiles = listFiles(SOURCE_LOCALE);

  const registry = existsSync(REGISTRY_FILE) ? readFileSync(REGISTRY_FILE, "utf8") : "";
  if (registry !== renderRegistry(sourceFiles)) {
    errors.push("src/i18n/registry.ts is out of date — run `yarn i18n:sync`");
  }

  for (const locale of locales) {
    const files = listFiles(locale);
    for (const extra of files.filter((f) => !sourceFiles.includes(f))) {
      errors.push(`[${locale}] ${extra}.json has no counterpart in ${SOURCE_LOCALE}/`);
    }
    for (const file of sourceFiles) {
      if (!files.includes(file)) {
        errors.push(`[${locale}] missing file ${file}.json`);
        continue;
      }
      const read = (l) =>
        flatten(JSON.parse(readFileSync(join(MESSAGES_DIR, l, `${file}.json`), "utf8")));
      const source = read(SOURCE_LOCALE);
      const target = read(locale);
      for (const key of Object.keys(source)) {
        if (!(key in target)) errors.push(`[${locale}] ${file}.json missing key "${key}"`);
        else if (typeof target[key] !== "string" || target[key].trim() === "")
          errors.push(`[${locale}] ${file}.json empty value at "${key}"`);
        else if (placeholders(source[key]) !== placeholders(target[key]))
          errors.push(
            `[${locale}] ${file}.json "${key}" placeholders differ: {${placeholders(source[key])}} vs {${placeholders(target[key])}}`
          );
      }
      for (const key of Object.keys(target)) {
        if (!(key in source)) errors.push(`[${locale}] ${file}.json has unknown key "${key}"`);
      }
    }
  }

  if (errors.length) {
    console.error(`i18n check failed (${errors.length}):\n  - ${errors.join("\n  - ")}`);
    process.exit(1);
  }
  console.log(`i18n check OK — ${locales.length} locales × ${sourceFiles.length} files`);
}

const command = process.argv[2];
if (command === "sync") sync();
else if (command === "check") check();
else {
  console.error("Usage: node scripts/i18n.mjs <sync|check>");
  process.exit(1);
}
